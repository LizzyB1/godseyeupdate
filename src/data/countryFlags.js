const REGIONAL_INDICATOR_BASE = 0x1f1e6; // 🇦 = 'A' + this offset

/**
 * Builds a flag emoji from an ISO 3166-1 alpha-2 code (e.g. "US" → 🇺🇸).
 * @param {string} iso2
 * @returns {?string}
 */
export function flagEmoji(iso2) {
  if (!/^[A-Za-z]{2}$/.test(iso2 || '')) return null;
  const code = iso2.toUpperCase();
  return String.fromCodePoint(
    REGIONAL_INDICATOR_BASE + (code.codePointAt(0) - 65),
    REGIONAL_INDICATOR_BASE + (code.codePointAt(1) - 65),
  );
}

/**
 * Resolves a `mmsiMid.js` flag-state name straight to its flag emoji.
 * @param {?string} countryName - As returned by `getFlagState`/`MID_TABLE`.
 * @returns {?string}
 */
export function flagEmojiForCountryName(countryName) {
  if (!countryName) return null;
  const iso2 = COUNTRY_TO_ISO2[countryName];
  return iso2 ? flagEmoji(iso2) : null;
}

/**
 * One-step MMSI → flag emoji, for callers that don't need the country name
 * too. Returns null for a malformed MMSI or an unmapped/reserved MID.
 * @param {string|number} mmsi
 * @param {(mmsi: string|number) => ?string} getFlagState - Injected to avoid
 *   a circular import with mmsiMid.js; pass its `getFlagState`.
 * @returns {?string}
 */
export function flagEmojiForMmsi(mmsi, getFlagState) {
  return flagEmojiForCountryName(getFlagState(mmsi));
}
